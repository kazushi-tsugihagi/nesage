-- ネサゲのデータベース（Cloudflare D1）。何度実行しても大丈夫なように IF NOT EXISTS にしている
CREATE TABLE IF NOT EXISTS likes (uid TEXT NOT NULL, item TEXT NOT NULL, created INTEGER NOT NULL, PRIMARY KEY (uid, item));
CREATE INDEX IF NOT EXISTS likes_item ON likes (item);
CREATE TABLE IF NOT EXISTS watches (uid TEXT NOT NULL, item TEXT NOT NULL, name TEXT, base INTEGER NOT NULL, PRIMARY KEY (uid, item));
CREATE TABLE IF NOT EXISTS subs (uid TEXT PRIMARY KEY, endpoint TEXT NOT NULL, created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS notices (id INTEGER PRIMARY KEY AUTOINCREMENT, uid TEXT NOT NULL, item TEXT NOT NULL, name TEXT, old INTEGER, new INTEGER, url TEXT, created INTEGER NOT NULL, seen INTEGER NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS notices_uid ON notices (uid, seen);
